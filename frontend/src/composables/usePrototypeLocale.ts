const updateDocumentLanguage = (value: PrototypeLocale) => {
  if (typeof document !== 'undefined') document.documentElement.lang = value
}

updateDocumentLanguage(locale.value)

export const usePrototypeLocale = () => {
  const setLocale = (value: PrototypeLocale) => {
    if (!supportedLocales.includes(value)) return
    locale.value = value
    if (typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, value)
    updateDocumentLanguage(value)
  }

  const t = (key: string, replacements: Record<string, string | number> = {}) => {
    let value = messages[locale.value][key] ?? messages.es[key] ?? key
    Object.entries(replacements).forEach(([name, replacement]) => {
      value = value.replace(`{${name}}`, String(replacement))
    })
    return value
  }

  return { locale, setLocale, t }
}
