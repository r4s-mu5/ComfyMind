const STORAGE_KEY = 'comfymind.prototype.locale'
const supportedLocales: PrototypeLocale[] = ['ca', 'es', 'en']

const getInitialLocale = (): PrototypeLocale => {
  if (typeof window === 'undefined') return 'es'

  try {
    const savedLocale = window.localStorage.getItem(STORAGE_KEY) as PrototypeLocale | null
    return savedLocale && supportedLocales.includes(savedLocale) ? savedLocale : 'es'
  } catch {
    return 'es'
  }
}

